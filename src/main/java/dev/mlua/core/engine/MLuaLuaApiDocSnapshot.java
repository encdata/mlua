package dev.mlua.core.engine;

import dev.mlua.common.enums.RegistrationPhase;
import dev.mlua.common.enums.ScriptType;
import dev.mlua.common.enums.Side;
import dev.mlua.core.MLuaContext;
import dev.mlua.core.MLuaRuntime;
import dev.mlua.core.require.MLuaModuleCache;
import dev.mlua.core.scheduler.MLuaTaskScheduler;
import dev.mlua.core.script.MLuaScript;
import dev.mlua.core.service.MLuaServiceRegistry;
import dev.mlua.module.MLuaModuleLoader;
import java.nio.file.Path;
import java.util.Map;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.TreeMap;
import org.luaj.vm2.Globals;
import org.luaj.vm2.LuaError;
import org.luaj.vm2.LuaTable;
import org.luaj.vm2.LuaValue;
import org.luaj.vm2.Varargs;
import org.luaj.vm2.lib.VarArgFunction;
import org.luaj.vm2.lib.jse.JsePlatform;

/** Builds offline API inventories from the same LuaJ bindings used by scripts. */
public final class MLuaLuaApiDocSnapshot {
    private MLuaLuaApiDocSnapshot() { }

    public static String generateHtml() {
        return generate().inventoryHtml();
    }

    public static DocumentationSnapshot generate() {
        MLuaModuleLoader modules = MLuaModuleLoader.get();
        modules.loadForDocumentation();
        StringBuilder html = new StringBuilder();
        java.util.Set<String> globalNames = new java.util.TreeSet<>(String.CASE_INSENSITIVE_ORDER);
        java.util.Set<String> enumNames = new java.util.TreeSet<>(String.CASE_INSENSITIVE_ORDER);
        html.append("<p>This build-time inventory is generated by crawling LuaJ globals, module bindings, and registered service tables. Runtime scans replace it with the services actually materialized by the running script.</p>");
        for (Side side : Side.values()) {
            if (side == Side.BOTH) continue;
            html.append("<h2>").append(side.name()).append(" bindings</h2>");
            MLuaLuaApiCrawler.CrawlResult crawl = crawlSide(modules, side);
            html.append(crawl.inventoryHtml());
            globalNames.addAll(crawl.globalNames());
            enumNames.addAll(crawl.enumNames());
        }
        return new DocumentationSnapshot(html.toString(), List.copyOf(globalNames), List.copyOf(enumNames));
    }

    private static MLuaLuaApiCrawler.CrawlResult crawlSide(MLuaModuleLoader modules, Side side) {
        modules.registerClasses(MLuaRuntime.get(), side);
        Path root = Path.of(".").toAbsolutePath().normalize();
        ScriptType scriptType = side == Side.CLIENT ? ScriptType.CLIENT : ScriptType.SERVER;
        MLuaScript script = new MLuaScript("mlua", scriptType, root,
            root.resolve("mlua-api-snapshot.lua"), "mlua-api-snapshot", "");
        MLuaServiceRegistry services = new MLuaServiceRegistry();
        modules.registerServices(services, side);
        MLuaContext context = new MLuaContext(script, side, RegistrationPhase.RUNTIME, services,
            new MLuaTaskScheduler(), new MLuaModuleCache(), null, root.resolve("run/mlua/data"));

        Globals globals = JsePlatform.standardGlobals();
        globals.set("warn", new VarArgFunction() {
            @Override public Varargs invoke(Varargs args) { return LuaValue.NONE; }
        });
        globals.set("print", new VarArgFunction() {
            @Override public Varargs invoke(Varargs args) { return LuaValue.NONE; }
        });
        globals.set("typeof", new VarArgFunction() {
            @Override public Varargs invoke(Varargs args) { return MLuaLuauTypes.typeName(args.arg1()); }
        });
        globals.set("assert", new VarArgFunction() {
            @Override public Varargs invoke(Varargs args) {
                if (!args.arg1().toboolean()) throw new LuaError(args.narg() > 1 ? args.arg(2).tojstring() : "assertion failed!");
                return args;
            }
        });
        globals.set("Require", new VarArgFunction() {
            @Override public Varargs invoke(Varargs args) { throw new LuaError("Require is unavailable in the offline API snapshot"); }
        });
        globals.set("Signal", MLuaLuaBindings.signalTable(globals, context.scheduler()));
        MLuaLuauTypes.install(globals);
        modules.contributeGlobals(globals, side);
        MLuaLuaBindings.bindContext(globals, context);
        LuaTable task = MLuaLuaBindings.taskTable(context.scheduler(), globals);
        globals.set("task", task);
        globals.set("wait", task.get("wait"));
        globals.set("Minecraft", MLuaLuaBindings.minecraftTable(context));
        modules.contributeContextGlobals(globals, context);

        Map<String, LuaTable> materialized = new TreeMap<>();
        Map<String, String> failures = new TreeMap<>();
        for (String name : services.names()) {
            try {
                materialized.put(name, MLuaLuaBindings.materializeServiceTable(context, name));
            } catch (Throwable error) {
                failures.put(name, error.getClass().getSimpleName() + ": " + String.valueOf(error.getMessage()));
            }
        }
        MLuaLuaApiCrawler.CrawlResult crawl = MLuaLuaApiCrawler.crawl(globals, materialized);
        StringBuilder result = new StringBuilder(crawl.inventoryHtml());
        if (!failures.isEmpty()) {
            result.append("<h3>Services unavailable in the offline snapshot</h3><ul>");
            failures.forEach((name, error) -> result.append("<li><code>").append(escape(name)).append("</code>: ")
                .append(escape(error)).append("</li>"));
            result.append("</ul>");
        }
        return new MLuaLuaApiCrawler.CrawlResult(result.toString(), crawl.globalNames(), crawl.enumNames());
    }

    private static String escape(String value) {
        return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace("\"", "&quot;").replace("'", "&#39;");
    }

    public record DocumentationSnapshot(String inventoryHtml, java.util.List<String> globalNames,
                                        java.util.List<String> enumNames) {
        public DocumentationSnapshot(String inventoryHtml) { this(inventoryHtml, java.util.List.of(), java.util.List.of()); }
        public DocumentationSnapshot(String inventoryHtml, java.util.List<String> globalNames) {
            this(inventoryHtml, globalNames, java.util.List.of());
        }
        public DocumentationSnapshot {
            globalNames = globalNames == null ? java.util.List.of() : java.util.List.copyOf(globalNames);
            enumNames = enumNames == null ? java.util.List.of() : java.util.List.copyOf(enumNames);
        }
    }
}
